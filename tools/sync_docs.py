#!/usr/bin/env python3
"""Sync federated component documentation from upstream repos.

Replaces mkdocs-multirepo-plugin (see CLAUDE.md §7 for why: the plugin is
inactive, requires an mkdocs.yml with a nav: section in every imported repo
that none of the eight component repos has, and its glob-based import would
sweep up vendored third-party SDK markdown alongside real docs).

This script instead walks an explicit allow-list (docs-sources.yml) of exact
upstream file paths, fetches each one, and writes it under docs/ with a front
matter banner recording exactly which upstream commit it came from. Output is
committed to this repo, so `mkdocs build` itself needs no network access and
is reproducible from a clean checkout.

Usage:
    tools/sync_docs.py              # sync everything in docs-sources.yml
    tools/sync_docs.py --check      # fetch nothing; verify manifest paths only

Only the standard library plus PyYAML is used. PyYAML is not a new
dependency — it already ships as a transitive dependency of mkdocs.
"""

from __future__ import annotations

import argparse
import datetime
import pathlib
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST_PATH = REPO_ROOT / "docs-sources.yml"
DOCS_DIR = REPO_ROOT / "docs"

USER_AGENT = "opennerve-site-sync-docs (https://github.com/axbaldwin1/opennerve-site)"

BANNER_TEMPLATE = """---
title: {title}
upstream_repo: {org}/{repo}
upstream_path: "{path}"
upstream_ref: {ref}
upstream_commit: {commit}
upstream_date: {date}
synced_edit_url: {edit_url}
---

!!! info "Synced from upstream — do not edit this file directly"
    This page is generated from
    [`{org}/{repo}`]({repo_url}) at `{path}`{commit_note}.
    To change it, edit the file upstream and re-run `tools/sync_docs.py`.
    Use the "Edit this page" link above to go straight to the upstream source.

{body}
"""

# Matches markdown links and images: [text](target) / ![alt](target)
_LINK_RE = re.compile(r"(!?\[[^\]]*\]\()([^)\s]+)((?:\s+\"[^\"]*\")?\))")


def log(msg: str) -> None:
    print(msg, file=sys.stderr)


def fatal(msg: str) -> None:
    log(f"error: {msg}")
    sys.exit(1)


def github_api(url: str) -> dict:
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": USER_AGENT,
            "Accept": "application/vnd.github+json",
        },
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        import json

        return json.loads(resp.read().decode("utf-8"))


def resolve_ref(org: str, repo: str, ref: str) -> tuple[str | None, str | None]:
    """Resolve a branch/tag to a commit sha + committer date.

    Best-effort: the GitHub REST API is rate-limited for unauthenticated
    callers (60 requests/hour), while raw.githubusercontent.com content
    fetches below are not. If this call fails — rate limit, network — we
    still sync content, just without a resolved commit to record. That's a
    degraded-but-usable state, not a hard failure: the file content is what
    actually matters, and a stale/missing commit pin is easy to spot and
    re-run later.
    """
    url = f"https://api.github.com/repos/{org}/{repo}/commits/{urllib.parse.quote(ref)}"
    try:
        data = github_api(url)
    except urllib.error.HTTPError as e:
        log(f"warning: could not resolve {org}/{repo}@{ref} to a commit ({e}); "
            f"syncing content without a commit pin")
        return None, None
    except urllib.error.URLError as e:
        log(f"warning: network error resolving {org}/{repo}@{ref} ({e}); "
            f"syncing content without a commit pin")
        return None, None
    sha = data.get("sha")
    date = data.get("commit", {}).get("committer", {}).get("date")
    return sha, date


def fetch_raw(org: str, repo: str, ref_or_sha: str, path: str) -> str:
    quoted = "/".join(urllib.parse.quote(part) for part in path.split("/"))
    url = f"https://raw.githubusercontent.com/{org}/{repo}/{ref_or_sha}/{quoted}"
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.read().decode("utf-8")
    except urllib.error.HTTPError as e:
        if e.code == 404:
            fatal(
                f"404 fetching {org}/{repo}@{ref_or_sha}:{path!r} — the path in "
                f"docs-sources.yml no longer exists upstream. Fix the manifest; "
                f"do not silently skip it."
            )
        raise


def derive_title(body: str, fallback: str) -> str:
    for line in body.splitlines():
        line = line.strip()
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def rewrite_relative_links(body: str, org: str, repo: str, ref_or_sha: str, src_dir: str) -> str:
    """Rewrite relative markdown links/images to absolute upstream URLs.

    Synced files land at a different depth under docs/components/... than
    their upstream location, so relative links (to images, sibling docs, etc.)
    would silently 404 on this site. Anything already absolute (http(s)://,
    mailto:, #fragment, or a site-root /path) is left untouched.
    """

    def repl(match: re.Match) -> str:
        prefix, target, suffix = match.group(1), match.group(2), match.group(3)
        if re.match(r"^(https?:)?//|^mailto:|^#|^/", target):
            return match.group(0)
        upstream_path = "/".join(
            filter(None, (src_dir, target))
        ) if src_dir else target
        # Images resolve to raw content so they render inline; other links
        # resolve to the GitHub blob view so a reader lands on a normal page.
        if prefix.startswith("!"):
            new_target = (
                f"https://raw.githubusercontent.com/{org}/{repo}/{ref_or_sha}/"
                + urllib.parse.quote(upstream_path)
            )
        else:
            new_target = (
                f"https://github.com/{org}/{repo}/blob/{ref_or_sha}/"
                + urllib.parse.quote(upstream_path)
            )
        return f"{prefix}{new_target}{suffix}"

    return _LINK_RE.sub(repl, body)


def sync_file(org: str, repo: str, ref: str, sha: str | None, date: str | None,
              src_path: str, dest_rel: str) -> None:
    ref_or_sha = sha or ref
    body = fetch_raw(org, repo, ref_or_sha, src_path)

    src_dir = str(pathlib.PurePosixPath(src_path).parent)
    if src_dir == ".":
        src_dir = ""
    body = rewrite_relative_links(body, org, repo, ref_or_sha, src_dir)

    repo_url = f"https://github.com/{org}/{repo}"
    edit_url = f"{repo_url}/blob/{ref_or_sha}/{urllib.parse.quote(src_path)}"
    title = derive_title(body, fallback=pathlib.PurePosixPath(dest_rel).stem)

    if sha:
        commit = sha[:7]
        commit_note = f" as of commit `{commit}`"
    else:
        commit = "null"
        commit_note = f" (ref `{ref}`, exact commit unresolved — see sync warnings)"

    out = BANNER_TEMPLATE.format(
        title=title,
        org=org,
        repo=repo,
        path=src_path,
        ref=ref,
        commit=commit,
        date=date or "null",
        edit_url=edit_url,
        repo_url=repo_url,
        commit_note=commit_note,
        body=body,
    )

    dest = DOCS_DIR / dest_rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(out, encoding="utf-8")
    log(f"  synced {src_path} -> docs/{dest_rel}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="validate the manifest without fetching or writing anything",
    )
    args = parser.parse_args()

    if not MANIFEST_PATH.exists():
        fatal(f"manifest not found: {MANIFEST_PATH}")

    manifest = yaml.safe_load(MANIFEST_PATH.read_text(encoding="utf-8"))
    sources = manifest.get("sources", [])
    if not sources:
        fatal("docs-sources.yml has no `sources:` entries")

    total = 0
    for source in sources:
        org = source["org"]
        repo = source["repo"]
        ref = source.get("ref", "main")
        files = source.get("files", {})
        if not files:
            continue

        log(f"{org}/{repo}@{ref}:")
        if args.check:
            for src_path, dest_rel in files.items():
                log(f"  would sync {src_path} -> docs/{dest_rel}")
            total += len(files)
            continue

        sha, date = resolve_ref(org, repo, ref)
        if sha:
            log(f"  resolved to commit {sha[:7]} ({date})")
        for src_path, dest_rel in files.items():
            sync_file(org, repo, ref, sha, date, src_path, dest_rel)
            total += 1

    log(f"done: {total} file(s) {'validated' if args.check else 'synced'}")


if __name__ == "__main__":
    main()
